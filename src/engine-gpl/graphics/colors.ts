/** Image::color2rgb: the colour of a name; null for "none" and for an unknown name. */
export function color2rgb(name: string): Col | null {
  if (name === 'none' || !Object.prototype.hasOwnProperty.call(RGBCOLORS, name)) return null;
  const c = RGBCOLORS[name];
  return [c[0], c[1], c[2]];
}

/** dump_image.cpp default_colors (DumpImage constructor), indexed by type % 16 (type 1 is red). */
