export type VtkFlavor = 'legacy' | 'xml';
export type VtkPrecision = 'single' | 'double';
export type VtkDataset = 'polydata' | 'unstructured' | 'rectilinear';

/** A point data array: ncomp values per point, interleaved (nums), or one string per point (strs). */
export interface VtkArray {
  name: string;
  kind: 'int' | 'double' | 'string';
  ncomp: number;
  nums: ArrayLike<number>;
  strs: string[];
}

/** Values per line in the text formats (vtk_writer.cpp PER_LINE). */
const PER_LINE = 9;
/** VTK cell type ids (vtkCellType.h): vertex and hexahedron. */
const VTK_VERTEX = 1;
const VTK_HEXAHEDRON = 12;

/**
 * Shortest decimal form that reads back as x, as C++ fmt "{}" prints it (vtk_writer.cpp fmt_double and append_value).
 * Single precision values are compared as floats. The same algorithm as fix saed/vtk (fix_saed_vtk.ts).
 */
export const shortestReal = (x: number, single: boolean): string => {
  if (Number.isNaN(x)) return 'nan';
  if (!Number.isFinite(x)) return x > 0 ? 'inf' : '-inf';
  if (x === 0) return Object.is(x, -0) ? '-0' : '0';
  const sign = x < 0 ? '-' : '';
  const a = Math.abs(x);
  let s = '';
  for (let p = 1; p <= (single ? 9 : 17); p++) {
    s = a.toExponential(p - 1);
    const back = Number(s);
    if (single ? Math.fround(back) === a : back === a) break;
  }
  const ePos = s.indexOf('e');
  const digits = s.slice(0, ePos).replace('.', '').replace(/0+$/, '') || '0';
  const exp = Number(s.slice(ePos + 1));
  if (exp < -4 || exp >= 16) {
    const mant = digits.length > 1 ? `${digits[0]}.${digits.slice(1)}` : digits;
    return `${sign}${mant}e${exp < 0 ? '-' : '+'}${String(Math.abs(exp)).padStart(2, '0')}`;
  }
  if (exp < 0) return `${sign}0.${'0'.repeat(-exp - 1)}${digits}`;
  if (digits.length > exp + 1) return `${sign}${digits.slice(0, exp + 1)}.${digits.slice(exp + 1)}`;
  return `${sign}${digits.padEnd(exp + 1, '0')}`;
};

/** Legacy values: nine per line, a space after each value and a newline after every ninth or the last (write_legacy_values). */
const legacyLines = (items: string[]): string => {
  const parts: string[] = [];
  for (let i = 0; i < items.length; i++) {
    parts.push(items[i], (i + 1) % PER_LINE === 0 ? '\n' : ' ');
  }
  if (items.length % PER_LINE !== 0) parts.push('\n');
  return parts.join('');
};

/** XML ASCII values: nine per line, each line indented (vtk_writer.cpp xml_values). */
const xmlLines = (items: string[], indent: number): string => {
  const pad = ' '.repeat(indent);
  const parts: string[] = [];
  for (let i = 0; i < items.length; i++) {
    if (i % PER_LINE === 0) parts.push(pad);
    parts.push(items[i], (i + 1) % PER_LINE === 0 ? '\n' : ' ');
  }
  if (items.length % PER_LINE !== 0) parts.push('\n');
  return parts.join('');
};

export class VtkWriter {
  private dataset: VtkDataset = 'polydata';
  private points: number[] = [];
  private npoints = 0;
  private ncells = 0;
  private cellType = VTK_VERTEX;
  private dims: [number, number, number] = [0, 0, 0];
  private coords: [number[], number[], number[]] = [[], [], []];
  private title = 'Generated by LAMMPS';
  private readonly arrays: VtkArray[] = [];

  constructor(private readonly flavor: VtkFlavor, private readonly precision: VtkPrecision) {}

  /** The title line: one line of at most 256 characters (vtk_writer.cpp set_title). */
  setTitle(title: string): void {
    this.title = title.slice(0, 256).replace(/[\n\r]/g, ' ');
  }

  /** One vertex cell per point: the polydata of dump vtk atoms (vtk_writer.cpp set_polydata). */
  setPolydata(xyz: number[]): void {
    this.setVertices(xyz, 'polydata');
  }

  /** The same vertices as an unstructured grid (dump vtu atoms, vtk_writer.cpp set_unstructured_grid). */
  setUnstructured(xyz: number[]): void {
    this.setVertices(xyz, 'unstructured');
  }

  /** The eight corners of a hexahedron in VTK order (vtk_writer.cpp set_hexahedron). */
  setHexahedron(corners: number[][]): void {
    this.points = corners.flat();
    this.npoints = 8;
    this.ncells = 1;
    this.cellType = VTK_HEXAHEDRON;
    this.dataset = 'unstructured';
  }

  /** A rectilinear grid with the given coordinates along each axis (vtk_writer.cpp set_rectilinear_grid). */
  setRectilinear(xc: number[], yc: number[], zc: number[]): void {
    this.coords = [xc, yc, zc];
    this.dims = [xc.length, yc.length, zc.length];
    this.npoints = this.dims[0] * this.dims[1] * this.dims[2];
    this.ncells = (this.dims[0] - 1) * (this.dims[1] - 1) * (this.dims[2] - 1);
    this.dataset = 'rectilinear';
  }

  /** A point data array; nums holds ncomp values per point (vtk_writer.cpp add_point_array). */
  addPointArray(array: VtkArray): void {
    const n = array.kind === 'string' ? array.strs.length : array.nums.length;
    if (n !== this.npoints * array.ncomp) {
      throw new Error(`VTK data array ${array.name} has ${n} values but ${this.npoints} points times ${array.ncomp} components are required`);
    }
    this.arrays.push(array);
  }

  /** The complete file text. */
  text(): string {
    return this.flavor === 'legacy' ? this.legacy() : this.xml();
  }

  private setVertices(xyz: number[], dataset: VtkDataset): void {
    if (xyz.length % 3) throw new Error('VTK point list is not a multiple of 3');
    this.points = xyz;
    this.npoints = xyz.length / 3;
    this.ncells = this.npoints;
    this.cellType = VTK_VERTEX;
    this.dataset = dataset;
  }

  /** Real values as the writer prints them: single precision rounds to float first. */
  private real(v: number): string {
    return this.precision === 'single' ? shortestReal(Math.fround(v), true) : shortestReal(v, false);
  }

  private reals(values: ArrayLike<number>): string[] {
    return Array.from(values, (v) => this.real(v));
  }

  private realType(): string {
    return this.precision === 'single' ? 'float' : 'double';
  }

  private xmlRealType(): string {
    return this.precision === 'single' ? 'Float32' : 'Float64';
  }

  private perCell(): number {
    return this.cellType === VTK_HEXAHEDRON ? 8 : 1;
  }

  private legacy(): string {
    const out: string[] = [`# vtk DataFile Version 5.1\n${this.title}\nASCII\n`];
    const real = this.realType();
    switch (this.dataset) {
      case 'polydata':
        out.push(`DATASET POLYDATA\nPOINTS ${this.npoints} ${real}\n`, legacyLines(this.reals(this.points)));
        out.push(this.legacyCells('VERTICES'));
        break;
      case 'unstructured':
        out.push(`DATASET UNSTRUCTURED_GRID\nPOINTS ${this.npoints} ${real}\n`, legacyLines(this.reals(this.points)));
        out.push(this.legacyCells('CELLS'));
        out.push(`CELL_TYPES ${this.ncells}\n`, legacyLines(Array(this.ncells).fill(String(this.cellType))));
        break;
      case 'rectilinear':
        out.push(`DATASET RECTILINEAR_GRID\nDIMENSIONS ${this.dims[0]} ${this.dims[1]} ${this.dims[2]}\n`);
        (['X', 'Y', 'Z'] as const).forEach((axis, d) => {
          out.push(`${axis}_COORDINATES ${this.dims[d]} ${real}\n`, legacyLines(this.reals(this.coords[d])));
        });
        break;
    }
    if (this.arrays.length) {
      out.push(`POINT_DATA ${this.npoints}\n`, `FIELD FieldData ${this.arrays.length}\n`);
      for (const a of this.arrays) {
        const type = a.kind === 'int' ? 'int' : a.kind === 'string' ? 'string' : real;
        out.push(`${a.name} ${a.ncomp} ${this.npoints} ${type}\n`);
        if (a.kind === 'string') out.push(a.strs.map((s) => `${s}\n`).join(''));
        else if (a.kind === 'int') out.push(legacyLines(Array.from(a.nums, (v) => String(v))));
        else out.push(legacyLines(this.reals(a.nums)));
      }
    }
    return out.join('');
  }

  /** The OFFSETS and CONNECTIVITY sections of a vertex or hexahedron set; the offsets start at zero (legacy). */
  private legacyCells(keyword: string): string {
    const per = this.perCell();
    const offsets: string[] = [];
    for (let i = 0; i <= this.ncells; i++) offsets.push(String(i * per));
    const conn: string[] = [];
    for (let i = 0; i < this.ncells * per; i++) conn.push(String(i));
    return `${keyword} ${this.ncells + 1} ${conn.length}\nOFFSETS vtktypeint64\n${legacyLines(offsets)}`
      + `CONNECTIVITY vtktypeint64\n${legacyLines(conn)}`;
  }

  private xml(): string {
    const grid = this.dataset === 'polydata' ? 'PolyData' : this.dataset === 'unstructured' ? 'UnstructuredGrid' : 'RectilinearGrid';
    const out: string[] = [`<?xml version="1.0"?>\n<VTKFile type="${grid}" version="0.1" byte_order="LittleEndian" header_type="UInt32">\n`];
    if (this.dataset === 'rectilinear') {
      const ext = `0 ${this.dims[0] - 1} 0 ${this.dims[1] - 1} 0 ${this.dims[2] - 1}`;
      out.push(`  <${grid} WholeExtent="${ext}">\n    <Piece Extent="${ext}">\n`);
    } else if (this.dataset === 'polydata') {
      out.push(`  <${grid}>\n    <Piece NumberOfPoints="${this.npoints}" NumberOfVerts="${this.ncells}" NumberOfLines="0" `
        + `NumberOfStrips="0" NumberOfPolys="0">\n`);
    } else {
      out.push(`  <${grid}>\n    <Piece NumberOfPoints="${this.npoints}" NumberOfCells="${this.ncells}">\n`);
    }
    out.push('      <PointData>\n', ...this.arrays.map((a) => this.xmlArray(a, 8)), '      </PointData>\n');
    out.push('      <CellData>\n      </CellData>\n');
    if (this.dataset === 'rectilinear') {
      out.push('      <Coordinates>\n');
      (['x', 'y', 'z'] as const).forEach((name, d) => {
        out.push(this.xmlData(this.xmlRealType(), name, 1, xmlLines(this.reals(this.coords[d]), 10), 8));
      });
      out.push('      </Coordinates>\n');
    } else {
      out.push('      <Points>\n', this.xmlData(this.xmlRealType(), 'Points', 3, xmlLines(this.reals(this.points), 10), 8), '      </Points>\n');
      out.push(this.xmlCells(this.dataset === 'polydata' ? 'Verts' : 'Cells'));
    }
    out.push(`    </Piece>\n  </${grid}>\n</VTKFile>\n`);
    return out.join('');
  }

  private xmlData(type: string, name: string, ncomp: number, payload: string, indent: number): string {
    const pad = ' '.repeat(indent);
    const comps = ncomp > 1 ? ` NumberOfComponents="${ncomp}"` : '';
    return `${pad}<DataArray type="${type}" Name="${name}"${comps} format="ascii">\n${payload}${pad}</DataArray>\n`;
  }

  private xmlArray(a: VtkArray, indent: number): string {
    const pad = ' '.repeat(indent);
    if (a.kind === 'string') {
      // string arrays use <Array>: the character codes of every string, each followed by a zero
      const codes: string[] = [];
      for (const s of a.strs) {
        for (let i = 0; i < s.length; i++) codes.push(String(s.charCodeAt(i) & 0xff));
        codes.push('0');
      }
      return `${pad}<Array type="String" Name="${a.name}" format="ascii">\n${xmlLines(codes, indent + 2)}${pad}</Array>\n`;
    }
    if (a.kind === 'int') return this.xmlData('Int32', a.name, a.ncomp, xmlLines(Array.from(a.nums, (v) => String(v)), indent + 2), indent);
    return this.xmlData(this.xmlRealType(), a.name, a.ncomp, xmlLines(this.reals(a.nums), indent + 2), indent);
  }

  /** The connectivity, offsets and (for unstructured grids) types of the cells; the XML offsets are end offsets. */
  private xmlCells(tag: string): string {
    const per = this.perCell();
    const offsets: string[] = [];
    for (let i = 0; i < this.ncells; i++) offsets.push(String((i + 1) * per));
    const conn: string[] = [];
    for (let i = 0; i < this.ncells * per; i++) conn.push(String(i));
    let out = `      <${tag}>\n`;
    out += this.xmlData('Int64', 'connectivity', 1, xmlLines(conn, 10), 8);
    out += this.xmlData('Int64', 'offsets', 1, xmlLines(offsets, 10), 8);
    if (tag === 'Cells') out += this.xmlData('UInt8', 'types', 1, xmlLines(Array(this.ncells).fill(String(this.cellType)), 10), 8);
    return `${out}      </${tag}>\n`;
  }
}
