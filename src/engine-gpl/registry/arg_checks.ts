/** The message of native's first check when a fix or compute command has the wrong number of words, else null. */
const nativeArgCheck = (what: 'fix' | 'compute', style: string, narg: number): string | null => {
  const c = (what === 'fix' ? FIX_ARG_CHECKS : COMPUTE_ARG_CHECKS)[style];
  if (!c) return null;
  const [kind, nums, message, page] = c;
  const bad = kind === 'min' ? narg < nums[0] : kind === 'only' ? !nums.includes(narg) : narg < nums[0] || narg > nums[1];
  return bad ? `${message.replace('{narg}', String(narg))}${page ? errorUrl(Number(page)) : ''}` : null;
};

export const HOOKS = {
  fix: (style: string, narg: number): string | null => nativeArgCheck('fix', style, narg),
  compute: (style: string, narg: number): string | null => nativeArgCheck('compute', style, narg),
};
