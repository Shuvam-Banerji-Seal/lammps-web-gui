import { describe, expect, it } from 'vitest';
import { Session } from '../src/engine/interpreter';

/*
 * dump vtk (src/engine-gpl/dump/dump_vtk.ts, ported from src/EXTRA-DUMP/dump_vtk.cpp at b332f28): the file layouts
 * (legacy, PolyData, UnstructuredGrid, the bounding box files), the attribute order and vector names, the dump_modify
 * keywords and the named refusals. Numeric parity with native LAMMPS is in tests/oracle/w196vtk_*.in.
 */

const BASE = `units lj
lattice fcc 0.8442
region box block 0 2 0 2 0 2
create_box 1 box
create_atoms 1 box
mass 1 1.0
velocity all create 1.44 87287 loop geom
pair_style lj/cut 2.5
pair_coeff 1 1 1.0 1.0 2.5
fix 1 all nve
`;

/** Runs the script and returns the files it wrote; a refused command rejects. */
const run = async (lines: string[]) => {
  const files = new Map<string, string>();
  const s = new Session({
    emit: () => {},
    writeFile: (n: string, t: string, ap: boolean) => files.set(n, (ap ? files.get(n) ?? '' : '') + t),
  } as never);
  await s.execute(`${BASE}${lines.join('\n')}\n`);
  return files;
};

const fileOf = (files: Map<string, string>, name: string): string => {
  const t = files.get(name);
  if (t === undefined) throw new Error(`no file ${name}; wrote ${[...files.keys()].join(', ')}`);
  return t;
};

describe('dump vtk: legacy and XML layouts', () => {
  it('writes the legacy PolyData file with deduplicated, enum-ordered arrays and the bounding box', async () => {
    const files = await run(['dump d all vtk 1 snap*.vtk id type vx vy vz id', 'run 0']);
    const t = fileOf(files, 'snap0.vtk');
    expect(t.startsWith('# vtk DataFile Version 5.1\nGenerated by LAMMPS\nASCII\nDATASET POLYDATA\nPOINTS 32 float\n')).toBe(true);
    expect(t).toContain('VERTICES 33 32\nOFFSETS vtktypeint64\n');
    expect(t).toContain('POINT_DATA 32\nFIELD FieldData 3\nid 1 32 int\n');
    expect(t).toContain('type 1 32 int\n');
    expect(t).toContain('v 3 32 float\n');
    expect(t.match(/^id 1 32 int$/gm)?.length).toBe(1);
    const box = fileOf(files, 'snap0_boundingBox.vtk');
    expect(box).toContain('DATASET RECTILINEAR_GRID\nDIMENSIONS 2 2 2\n');
  });

  it('writes XML PolyData with the xs ys zs triple as the 3-component array s, and the .vtr box', async () => {
    const files = await run(['dump e all vtk 1 xm*.vtp id xs ys zs', 'run 0']);
    const t = fileOf(files, 'xm0.vtp');
    expect(t.startsWith('<?xml version="1.0"?>\n<VTKFile type="PolyData" version="0.1" byte_order="LittleEndian" header_type="UInt32">\n  <PolyData>\n')).toBe(true);
    expect(t).toContain('NumberOfPoints="32" NumberOfVerts="32"');
    expect(t).toContain('<DataArray type="Float32" Name="s" NumberOfComponents="3" format="ascii">');
    expect(t).toContain('<DataArray type="Float32" Name="Points" NumberOfComponents="3" format="ascii">');
    expect(t).toContain('<Verts>');
    const box = fileOf(files, 'xm0_boundingBox.vtr');
    expect(box).toContain('<RectilinearGrid WholeExtent="0 1 0 1 0 1">');
  });

  it('writes .vtu with the ix iy iz array i (int, 3 components) and the cell types', async () => {
    const files = await run(['dump f all vtk 1 xu*.vtu id ix iy iz', 'run 0']);
    const t = fileOf(files, 'xu0.vtu');
    expect(t).toContain('<VTKFile type="UnstructuredGrid"');
    expect(t).toContain('<DataArray type="Int32" Name="i" NumberOfComponents="3" format="ascii">');
    expect(t).toContain('<DataArray type="UInt8" Name="types" format="ascii">');
    expect(fileOf(files, 'xu0_boundingBox.vtr')).toContain('RectilinearGrid');
  });

  it('writes the hexahedron bounding box of a triclinic box (legacy and vtu)', async () => {
    const files = await run([
      'change_box all triclinic',
      'dump a all vtk 1 tri*.vtk id', 'dump b all vtk 1 tri*.vtu id', 'run 0',
    ]);
    const box = fileOf(files, 'tri0_boundingBox.vtk');
    expect(box).toContain('DATASET UNSTRUCTURED_GRID\nPOINTS 8 float\n');
    expect(box).toContain('CELLS 2 8\n');
    expect(box).toContain('CELL_TYPES 1\n12 \n');
    expect(fileOf(files, 'tri0_boundingBox.vtu')).toContain('<UnstructuredGrid>');
  });

  it('replaces a % in a legacy file name by 0 (native dump0.vtk)', async () => {
    const files = await run(['dump p all vtk 1 pc%.vtk id', 'run 0']);
    expect(fileOf(files, 'pc0.vtk')).toContain('DATASET POLYDATA');
    expect(fileOf(files, 'pc0_boundingBox.vtk')).toContain('RECTILINEAR_GRID');
  });

  it('pads the timestep of a * file name with dump_modify pad', async () => {
    const files = await run(['dump d all vtk 1 pad*.vtk id', 'dump_modify d pad 3', 'run 1']);
    expect([...files.keys()].filter((k) => /^pad\d{3}\.vtk$/.test(k)).length).toBe(2);
  });
});

describe('dump vtk: dump_modify keywords', () => {
  it('uses label as the title line, double yes for double values, element names and region', async () => {
    const files = await run([
      'dump d all vtk 1 mo*.vtk id element', 'dump_modify d label cells double yes element Ar region box',
      'run 0',
    ]);
    const t = fileOf(files, 'mo0.vtk');
    expect(t.split('\n')[1]).toBe('cells');
    expect(t).toContain('POINTS 32 double\n');
    expect(t).toContain('element 1 32 string\nAr\n');
  });

  it('selects atoms by a region and by a threshold, in the POINT_DATA count', async () => {
    const files = await run([
      'region half block 0 0.5 INF INF INF INF', 'dump d all vtk 1 rg*.vtk id', 'dump_modify d region half', 'run 0',
    ]);
    const m = /POINT_DATA (\d+)/.exec(fileOf(files, 'rg0.vtk'));
    expect(m).not.toBeNull();
    expect(Number(m![1])).toBeGreaterThan(0);
    expect(Number(m![1])).toBeLessThan(32);
  });
});

describe('dump vtk: refusals name the keyword', () => {
  it('rejects an unknown attribute', async () => {
    await expect(run(['dump d all vtk 1 bad.vtk foo', 'run 0'])).rejects.toThrow('Invalid attribute foo in dump vtk command');
  });
  it('rejects a per-atom property that is not allocated', async () => {
    await expect(run(['dump d all vtk 1 bad.vtk mol', 'run 0'])).rejects.toThrow(/molecular atom_style/);
  });
  it('rejects dump_modify binary yes', async () => {
    await expect(run(['dump d all vtk 1 bad.vtk id', 'dump_modify d binary yes', 'run 0'])).rejects.toThrow(/binary yes is not supported/);
  });
  it('rejects a dump_modify keyword that dump vtk does not take', async () => {
    await expect(run(['dump d all vtk 1 bad.vtk id', 'dump_modify d scale no', 'run 0'])).rejects.toThrow(/dump_modify scale is not supported/);
  });
  it('rejects thresh LAST', async () => {
    await expect(run(['dump d all vtk 1 bad.vtk id', 'dump_modify d thresh vx > LAST', 'run 0'])).rejects.toThrow(/thresh LAST/);
  });
  it('rejects a % file name with an XML format', async () => {
    await expect(run(['dump d all vtk 1 bad%.vtp id', 'run 0'])).rejects.toThrow(/"%" file name with .vtp or .vtu/);
  });
  it('is not a write_dump style', async () => {
    await expect(run(['write_dump all vtk bad.vtk id'])).rejects.toThrow(/write_dump style 'vtk' is not supported/);
  });
});
