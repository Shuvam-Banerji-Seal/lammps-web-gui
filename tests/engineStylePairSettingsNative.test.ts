/*
 * Each pair style with no arguments or with one word, foo, and each bond, angle, dihedral and improper style with foo,
 * read as native LAMMPS reads them: the style's constructor checks (atom attributes, unit style), then its
 * settings(): the argument count first, then the words (src/pair_*.cpp, src/bond_*.cpp and the like at b332f28;
 * a style that takes no settings reports the first word, Bond::settings in src/bond.cpp). Measured with native LAMMPS
 * (/home/roy/.local/bin/lmp, b332f28): each row is the last line of an input after PREAMBLE and the first line of
 * native's error message (null when native accepts the command). Not compared here: the styles of packages the
 * native binary lacks and those native stops on with a crash.
 */

const PREAMBLE = "units lj\natom_style full\nregion box block 0 4 0 4 0 4\ncreate_box 1 box bond/types 1 angle/types 1 dihedral/types 1 improper/types 1\ncreate_atoms 1 single 1 1 1\nmass 1 1.0\n";

const firstError = async (input: string): Promise<string | null> => {
  const s = new Session({ emit: () => {}, writeFile: () => {} } as never);
  // the engine's message starts with the line of the input ("line N: "), which native prints elsewhere
  try { await s.execute(input); } catch (e) { return (e as Error).message.split('\n')[0].replace(/^line \d+: /, ''); }
  return null;
};

