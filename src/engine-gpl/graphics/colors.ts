/** Image::element2color: the colour of an element, or null when it is not in the table. */
export function element2color(name: string): Col | null {
  if (!Object.prototype.hasOwnProperty.call(ELEMENTDATA, name)) return null;
  const c = ELEMENTDATA[name][0];
  return [c[0], c[1], c[2]];
}

/** Image::element2diam: the covalent diameter of an element, 0 when it is not in the table. */
export function element2diam(name: string): number {
  return Object.prototype.hasOwnProperty.call(ELEMENTDATA, name) ? ELEMENTDATA[name][1] : 0;
}

/** static_cast<int>(c * 255.0): the 8-bit value of a channel (Image::clear, backcolor, draw_pixel). */
export const byteOf = (c: number): number => Math.trunc(c * 255.0);
