const copysign = (v: number, s: number): number => {
  const a = Math.abs(v);
  return s < 0 || Object.is(s, -0) ? -a : a;
};

/** do_cos of s_sin.c: cos(x + dx). */
const doCos = (x: number, dx: number): number => {
  if (x < 0) dx = -dx;
  const ux = big + Math.abs(x);
  x = Math.abs(x) - (ux - big) + dx;
  F[0] = ux;
  const k = U[0] << 2;
  const xx = x * x;
  const s = x + x * xx * (sn3 + xx * sn5);
  const c = xx * (cs2 + xx * (cs4 + xx * cs6));
  const sn = TAB[k], ssn = TAB[k + 1], cs = TAB[k + 2], ccs = TAB[k + 3];
  const cor = (ccs - s * ssn - cs * c) - sn * s;
  return cs + cor;
};

/** do_sin of s_sin.c: sin(x + dx). */
const doSin = (x: number, dx: number): number => {
  const xold = x;
  if (Math.abs(x) < 0.126) {
    // TAYLOR_SIN (x * x, x, dx)
    const xx = x * x;
    const poly = ((((s5 * xx + s4) * xx + s3) * xx + s2) * xx) + s1;
    const t = ((poly * x - 0.5 * dx) * xx + dx);
    return x + t;
  }
  if (x <= 0) dx = -dx;
  const ux = big + Math.abs(x);
  x = Math.abs(x) - (ux - big);
  F[0] = ux;
  const k = U[0] << 2;
  const xx = x * x;
  const s = x + (dx + x * xx * (sn3 + xx * sn5));
  const c = x * dx + xx * (cs2 + xx * (cs4 + xx * cs6));
  const sn = TAB[k], ssn = TAB[k + 1], cs = TAB[k + 2], ccs = TAB[k + 3];
  const cor = (ssn + s * ccs - sn * c) + cs * s;
  return copysign(sn + cor, xold);
};

