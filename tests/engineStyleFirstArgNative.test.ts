/*
 * Each fix and compute style given one word, foo, after its style name, read as native LAMMPS reads it: the first
 * check that word meets (a number read with utils::numeric or utils::inumeric, a keyword, a compute or group ID, an
 * atom attribute; src/fix_*.cpp and src/compute_*.cpp at b332f28). Measured with native LAMMPS
 * (/home/roy/.local/bin/lmp, b332f28): each row is the last line of an input after PREAMBLE and the first line of
 * native's error message (null when native accepts the command). Not compared here: the styles of packages the
 * native binary lacks and those native stops on with a crash.
 */

const PREAMBLE = "units lj\natom_style full\nregion box block 0 4 0 4 0 4\ncreate_box 1 box\ncreate_atoms 1 single 1 1 1\nmass 1 1.0\n";

const firstError = async (input: string): Promise<string | null> => {
  const s = new Session({ emit: () => {}, writeFile: () => {} } as never);
  // the engine's message starts with the line of the input ("line N: "), which native prints elsewhere
  try { await s.execute(input); } catch (e) { return (e as Error).message.split('\n')[0].replace(/^line \d+: /, ''); }
  return null;
};

