/*
 * Bonded styles without coefficients for every type, read as native LAMMPS reads them: Bond::init, Angle::init,
 * Dihedral::init and Improper::init (src/bond.cpp and friends at b332f28) stop before the style's own init with
 * "<Kind> coeffs are not set. Status:" when no command gave the style coefficients and "All <kind> coeffs are not set.
 * Status:" when a type has none. Measured with native LAMMPS (/home/roy/.local/bin/lmp, b332f28): each row is the
 * style and coefficient lines after BOX, then run 0, and the first line of native's error. Not compared here: the /omp
 * aliases, which native refuses without the package omp command.
 */

const BOX = "units real\natom_style full\nregion box block 0 10 0 10 0 10\ncreate_box 2 box bond/types 2 angle/types 2 dihedral/types 2 improper/types 2\ncreate_atoms 1 single 1 1 1\nmass * 1.0\n";
const TABLES = ['w216tb_bond.table', 'w216tb_angle.table', 'w216tb_dihedral.table'];

const outcome = async (lines: string): Promise<string> => {
  const s = new Session({ emit: () => {}, writeFile: () => {} } as never);
  for (const f of TABLES) s.addFile(f, readFileSync(join(__dirname, 'oracle', f), 'utf8'));
  // the engine's message starts with the line of the input ("line N: "), which native prints elsewhere
  try { await s.execute(BOX + lines + '\nrun 0\n'); } catch (e) { return 'ERROR: ' + (e as Error).message.split('\n')[0].replace(/^line \d+: /, ''); }
  return 'OK';
};

