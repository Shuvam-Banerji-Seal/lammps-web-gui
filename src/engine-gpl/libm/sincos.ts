/** reduce_sincos of s_sin.c (|x| < 105414350): writes a + da (redA, redDa) and returns the quadrant. */
const reduceSincos = (x: number): number => {
  const t = (x * hpinv + toint);
  const xn = t - toint;
  F[0] = t;
  const n = U[0] & 3;
  const y = (x - xn * mp1) - xn * mp2;
  let t1 = xn * pp3;
  const t2 = y - t1;
  let db = (y - t2) - t1;
  t1 = xn * pp4;
  const b = t2 - t1;
  db += (t2 - b) - t1;
  redA = b;
  redDa = db;
  return n;
};

